"""Customer fraud reports: find what the active rules missed and turn it into an investigation.

Customers report payments they did not make (demo bank "Report fraud").
Reports are stored as labelled test cases. When enough reported frauds slip
past the active rules (baseline + approved), code writes a factual digest of
what those payments have in common and the agent investigates it like any
other advisory. The digest is written by code from the reports only, so every
sentence can be quote-verified, and it never contains personal data.
"""

from __future__ import annotations

import hashlib
import statistics
from datetime import date

from pydantic import BaseModel

from app.intel.advisories import Advisory
from app.rule_lab import TestCase
from app.rules.engine import evaluate_rule
from app.rules.models import Rule

MIN_MISSED_REPORTS = 3
MAX_DIGEST_REPORTS = 50


class ReportsSummary(BaseModel):
    reports: int
    missed_by_active_rules: int
    ready_to_investigate: bool
    min_missed_reports: int = MIN_MISSED_REPORTS
    digest_advisory_id: str | None
    digest_preview: str | None


def missed_reports(reports: list[TestCase], active_rules: list[Rule]) -> list[TestCase]:
    """Reported frauds that no active rule flags."""
    return [
        case for case in reports
        if case.expected == "fraud" and not any(evaluate_rule(rule, case.transaction) for rule in active_rules)
    ]


def _share(cases: list[TestCase], test) -> str:
    hits = sum(1 for case in cases if test(case.transaction))
    return f"{hits} of {len(cases)}"


def digest_text(cases: list[TestCase]) -> str:
    """Plain, verifiable sentences about the missed reports (no names, cards, or free text)."""
    t = [case.transaction for case in cases]
    amounts = [x.amount for x in t if x.amount is not None]
    lines = [
        f"Customers reported {len(cases)} payments as fraud that the bank's active rules did not stop.",
        f"{_share(cases, lambda x: x.card_present == 0)} reported payments were card-not-present (online).",
        f"{_share(cases, lambda x: x.new_device == 1)} reported payments came from a device never seen before on the account.",
        f"{_share(cases, lambda x: x.new_payee == 1)} reported payments went to a payee or merchant the account had never paid before.",
        f"{_share(cases, lambda x: x.days_since_sim_change is not None and x.days_since_sim_change <= 3)} reported payments happened within 3 days of a SIM change on the customer's phone number.",
        f"{_share(cases, lambda x: (x.credential_resets_24h or 0) >= 1)} reported payments followed a password, PIN, or SMS credential reset in the previous 24 hours.",
        f"{_share(cases, lambda x: (x.transactions_1h or 0) >= 3)} reported payments were part of a burst of three or more payments within one hour.",
        f"{_share(cases, lambda x: (x.declined_attempts_24h or 0) >= 1)} reported payments followed at least one declined attempt in the previous 24 hours.",
        f"{_share(cases, lambda x: x.hour_of_day is not None and (x.hour_of_day >= 22 or x.hour_of_day <= 5))} reported payments were made between 22:00 and 05:59 local time.",
    ]
    if amounts:
        lines.append(
            f"Reported amounts ranged from {min(amounts):.2f} to {max(amounts):.2f}, with a median of {statistics.median(amounts):.2f}."
        )
    return " ".join(lines)


def digest_advisory(cases: list[TestCase]) -> Advisory:
    """An advisory built from missed reports; its id changes whenever the set of reports changes."""
    cases = sorted(cases, key=lambda case: case.created_at)[-MAX_DIGEST_REPORTS:]
    key = hashlib.sha256(",".join(case.case_id for case in cases).encode()).hexdigest()[:12]
    return Advisory(
        advisory_id=f"customer-reports-{key}",
        title=f"Customer fraud reports missed by active rules ({len(cases)} reports)",
        publisher="RulePilot demo bank: customer fraud reports",
        source_url=f"https://rulepilot.invalid/customer-reports/{key}",
        published_date=date.today().isoformat(),
        retrieved_at=date.today().isoformat(),
        source_type="customer_reports",
        rights_note="Generated by RulePilot code from customer fraud reports in the demo bank; no personal data.",
        excerpt=digest_text(cases),
    )


def summarize(reports: list[TestCase], active_rules: list[Rule], investigated_ids: set[str]) -> tuple[ReportsSummary, list[TestCase], Advisory | None]:
    missed = missed_reports(reports, active_rules)
    advisory = digest_advisory(missed) if len(missed) >= MIN_MISSED_REPORTS else None
    ready = advisory is not None and advisory.advisory_id not in investigated_ids
    return ReportsSummary(
        reports=len(reports),
        missed_by_active_rules=len(missed),
        ready_to_investigate=ready,
        digest_advisory_id=advisory.advisory_id if advisory else None,
        digest_preview=advisory.excerpt if advisory else None,
    ), missed, advisory
